def generate():
    questions=[]; s_num=j_num=m_num=0; s_serial=0
    for fact_index,fact in enumerate(FACTS):
        fact['fact_id']=f'CON-{fact_index+1:02d}'
        assert len(fact['single'])==5 and len(fact['sw'])==5
        assert len(fact['multi'])==5 and len(fact['mt'])==5 and len(fact['ma'])==5
        assert 2<=sum(fact['mt'])<=4
        # Four scenario/prompt variants per fact produce 100 single-choice items.
        for variant in range(4):
            scene=scene_for(fact_index,variant)
            prompt=question_text(fact,scene,variant)
            correct_letter=LETTERS[s_serial%5]
            wrongs=[fact['single'][j] for j in range(5) if j!=fact['sc']]
            ordered=[]; wi=iter(wrongs)
            for letter in LETTERS:
                ordered.append(fact['single'][fact['sc']] if letter==correct_letter else next(wi))
            options={letter:ordered[i] for i,letter in enumerate(LETTERS)}
            audit={}
            wrong_iter=iter([j for j in range(5) if j!=fact['sc']])
            for letter in LETTERS:
                if letter==correct_letter:
                    audit[letter]={'truth':True,'basis':fact['sw'][fact['sc']]}
                else:
                    audit[letter]={'truth':False,'basis':fact['sw'][next(wrong_iter)]}
            s_num+=1; s_serial+=1
            questions.append(make_question(f'X3C-S{s_num:03d}','s',s_num,prompt,options,[correct_letter],fact,audit=audit))
        # One assertion per fact; alternate truth by fact index for global 13/12 balance.
        scene=scene_for(fact_index,4)
        truth=fact_index%2==0
        assertion=fact['judge_t'] if truth else fact['judge_f']
        rationale=fact['jt'] if truth else fact['jf']
        j_num+=1
        questions.append(make_question(f'X3C-J{j_num:03d}','j',j_num,
            f'在{scene}时，判断：{assertion}',{},['T' if truth else 'F'],fact,
            statement_audit={'truth':truth,'basis':rationale}))
        # One multi-select per fact; stable seeded shuffle with semantic-index mapping.
        scene=scene_for(fact_index,5)
        permutation=list(range(5)); random.Random(0xC0CE+fact_index).shuffle(permutation)
        options={LETTERS[pos]:fact['multi'][semantic] for pos,semantic in enumerate(permutation)}
        sem={LETTERS[pos]:semantic for pos,semantic in enumerate(permutation)}
        truths={letter:bool(fact['mt'][semantic]) for letter,semantic in sem.items()}
        answers=sorted(letter for letter,value in truths.items() if value)
        audit={letter:{'truth':truths[letter],'basis':fact['ma'][sem[letter]]} for letter in LETTERS}
        m_num+=1
        questions.append(make_question(f'X3C-M{m_num:03d}','m',m_num,
            f'在{scene}时，关于{fact["topic"]}，以下哪些说法或做法正确？（多选）',options,answers,fact,
            audit=audit,semantic_index=sem))
    validate(questions)
    return questions


def validate(questions):
    assert len(questions)==150
    assert {t:sum(q['type']==t for q in questions) for t in LABEL}=={'s':100,'j':25,'m':25}
    ids=[q['id'] for q in questions]
    assert len(ids)==len(set(ids)) and all(re.fullmatch(r'X3C-[SJM]\d{3}',x) for x in ids)
    assert len({q['fact_id'] for q in questions})==25
    assert all(q['origin']=='extension' and q['standard_schema']=='T3-theory-v1' for q in questions)
    stems=[re.sub(r'\s+','',q['question']) for q in questions]
    assert len(stems)==len(set(stems))
    original=json.loads((Path(__file__).resolve().parents[2]/'刷题工具数据'/'data'/'theory_questions.json').read_text(encoding='utf-8'))
    original_stems={re.sub(r'\s+','',q['question']) for q in original}
    assert not (set(stems)&original_stems)
    for q in questions:
        assert q['fact_id'] and q['fact_basis'] and q['source_urls']
        assert q['explanation'] and q['knowledge_point']
        if q['type'] in ('s','m'):
            assert list(q['options'])==list(LETTERS) and len(set(q['options'].values()))==5
            assert set(q['option_audit'])==set(LETTERS)
            assert all(q['option_audit'][k]['truth'] == (k in q['answer_values']) for k in LETTERS)
        if q['type']=='s':
            assert len(q['answer_values'])==1 and q['answer'] in q['options']
        elif q['type']=='m':
            assert 2<=len(q['answer_values'])<=4 and q['answer']==''.join(q['answer_values'])
            assert sorted(q['semantic_index'].values())==list(range(5))
        else:
            assert q['options']=={} and q['answer'] in ('T','F')
            assert q['statement_audit']['truth']==(q['answer']=='T')
    singles=[q for q in questions if q['type']=='s']
    assert {letter:sum(q['answer']==letter for q in singles) for letter in LETTERS}=={letter:20 for letter in LETTERS}
    judges=[q for q in questions if q['type']=='j']
    assert sum(q['answer']=='T' for q in judges)==13
    assert sum(q['answer']=='F' for q in judges)==12


