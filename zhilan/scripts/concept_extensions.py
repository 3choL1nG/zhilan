def make_question(qid, typ, number, text, options, answer_values, fact, audit=None, statement_audit=None, semantic_index=None):
    item={
        'standard_schema':'T3-theory-v1', 'id':qid, 'level':3, 'type':typ,
        'type_label':LABEL[typ], 'number':number, 'question':text,
        'options':options, 'answer':''.join(answer_values), 'answer_values':answer_values,
        'explanation':fact['fact'], 'knowledge_point':fact['topic'], 'origin':'extension',
        'fact_id':fact['fact_id'], 'fact_basis':fact['fact'],
        'source_urls':fact['sources'],
    }
    if audit is not None:
        item['option_audit']=audit
    if statement_audit is not None:
        item['statement_audit']=statement_audit
    if semantic_index is not None:
        item['semantic_index']=semantic_index
    return item


def question_text(fact, scene, variant):
    form=FORMS[variant%len(FORMS)]
    return form.format(scene=scene,task=fact['task'])


